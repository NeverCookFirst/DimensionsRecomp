"""Build private vertex-shader variants for UBYTE4 integer inputs read as floats.

Xenos vertex shaders only have float registers: an integer (non-normalized)
8_8_8_8 vertex fetch delivers float(0..255). D3D12 has no USCALED format, so the
native declaration binds those elements as R8G8B8A8_UINT while the translated
shader declares float4 inputs - an undefined integer/float signature mismatch
(observed: Chima VS 500E11F5871DD2AA, stretched spikes). Each variant declares
the selected inputs as int4 and converts them with float() on entry (the
pipeline binds unsigned UBYTE4 as R8G8B8A8_UINT, signed BYTE4 as _SINT); every
other line of the translated source is unchanged. No game or GPU is started.

Usage:
  build_integer_input_bank.py OUTPUT.inc --dxc DXC \
      --shader SOURCE.hlsl:SEMANTIC[,SEMANTIC...] [--shader ...]
SEMANTIC is e.g. TEXCOORD1, TANGENT0, BLENDWEIGHT0. The mask bit layout must
match IntegerInputMaskBit() in rexlego/src/gpu_native/integer_inputs.cpp.
"""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess

# Keep in sync with integer_inputs.cpp.
BITS = {f'TEXCOORD{i}': i for i in range(8)}
BITS.update({'TANGENT0': 8, 'TANGENT1': 9, 'BLENDWEIGHT0': 10, 'COLOR0': 11,
             'COLOR1': 12, 'NORMAL0': 13, 'BINORMAL0': 14})


def variant_source(text, semantics):
    head = text.index('void main(')
    body = text.index('{', text.index(')', text.index('out float4 oPos', head)))
    signature = text[head:body]
    conversions = []
    for semantic in semantics:
        pattern = r'\bin\s+float4\s+(\w+)\s*:\s*' + semantic + r'\b'
        found = re.findall(pattern, signature)
        if len(found) != 1:
            raise ValueError(f'Expected one float4 {semantic} input')
        name = found[0]
        signature = re.sub(pattern, f'in int4 {name}_integer : {semantic}', signature)
        conversions.append(f'\tfloat4 {name} = float4({name}_integer);\n')
    return text[:head] + signature + '{\n' + ''.join(conversions) + text[body + 1:]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('output', type=Path)
    p.add_argument('--dxc', type=Path, required=True)
    p.add_argument('--shader', action='append', required=True)
    a = p.parse_args()
    work = a.output.with_suffix('.work')
    work.mkdir(parents=True, exist_ok=True)
    entries, blob, records = [], bytearray(), []
    for spec_arg in a.shader:
        path_text, semantics_text = spec_arg.rsplit(':', 1)
        path = Path(path_text)
        semantics = semantics_text.split(',')
        mask = 0
        for semantic in semantics:
            mask |= 1 << BITS[semantic]
        text = path.read_text()
        match = re.search(r'// vertex shader\s+hash=0x([0-9A-Fa-f]+)', text[:300])
        if not match or 'packoffset(c38)' not in text:
            raise ValueError('Expected an ABI624 translated vertex shader: ' + str(path))
        old = 'uint g_SpecConstants() { return 0; }'
        if text.count(old) != 1:
            raise ValueError('Expected one resolved specialization')
        shader_hash = int(match[1], 16)
        for spec in range(2):
            source = variant_source(text.replace(old, f'uint g_SpecConstants() {{ return {spec}; }}'), semantics)
            stem = f'{shader_hash:016X}-vs-{spec}-int{mask:04X}'
            hlsl = work / (stem + '.hlsl')
            dxil = work / (stem + '.dxil')
            hlsl.write_text(source)
            subprocess.run([str(a.dxc), str(hlsl), '-T', 'vs_6_0', '-E', 'main',
                            '-DREBLUE_RECOMP', '-DLEGO_NATIVE_GPU', '-HV', '2021',
                            '-Wno-ignored-attributes', '-Fo', str(dxil)],
                           check=True, capture_output=True, timeout=120)
            disassembly = subprocess.run([str(a.dxc), '-dumpbin', str(dxil)], check=True,
                                         capture_output=True, text=True, timeout=30).stdout
            for semantic in semantics:
                name, index = re.fullmatch(r'([A-Z]+)(\d+)', semantic).groups()
                if not re.search(rf'^; {name}\s+{index}\s+\w+\s+\d+\s+NONE\s+int', disassembly, re.M):
                    raise ValueError(f'{stem}: {semantic} is not a uint input in the compiled signature')
            data = dxil.read_bytes()
            while len(blob) % 16:
                blob.append(0)
            entries.append((shader_hash, spec, mask, len(blob), len(data)))
            records.append(dict(hash=f'{shader_hash:016X}', spec=spec, mask=f'{mask:04X}',
                                semantics=semantics, source=str(path),
                                source_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                                dxil_sha256=hashlib.sha256(data).hexdigest()))
            blob.extend(data)
    entries.sort()
    lines = ['// Generated by tools/gpu-aot/build_integer_input_bank.py. Do not edit.',
             '// ' + '; '.join(f"{r['hash']} spec{r['spec']} mask {r['mask']} {','.join(r['semantics'])}"
                                for r in records),
             'static const IntegerInputEntry kIntegerInputEntries[] = {']
    lines += [f'  {{0x{h:016X}ull, {s}u, 0x{m:04X}u, {o}u, {n}u}},' for h, s, m, o, n in entries]
    lines += ['};', 'alignas(16) static const unsigned char kIntegerInputBlob[] = {']
    for i in range(0, len(blob), 24):
        lines.append('  ' + ','.join(str(b) for b in blob[i:i + 24]) + ',')
    lines += ['};', '']
    a.output.write_text('\n'.join(lines))
    print(f'{len(entries)} variants, {len(blob)} bytes -> {a.output}')


if __name__ == '__main__':
    main()
